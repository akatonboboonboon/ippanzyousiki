function make(
  category: CategoryId,
  key: string,
  topic: string,
  rows: Row[],
): Question[] {
  return rows.map(([prompt, original, explanation, source, alt], index) => {
    const difficulty: Difficulty =
      index < 6 ? "easy" : index < 12 ? "normal" : "hard";
    const number = index < 6 ? index + 1 : index < 12 ? index - 5 : index - 11;
    const answer = index % 4;
    const choices = [
      ...original.slice(4 - answer),
      ...original.slice(0, 4 - answer),
    ] as Question["choices"];
    return {
      id: `v2-${category}-familiar-${key}-${difficulty}-${String(number).padStart(3, "0")}`,
      category,
      difficulty,
      topic,
      prompt,
      choices,
      answer,
      explanation,
      source,
      ...(alt
        ? {
            image: {
              src: `quiz/familiar-${key}-${String(number).padStart(2, "0")}.svg`,
              alt,
              caption: "学習用の模式図",
            },
          }
        : {}),
    };
  });
}

