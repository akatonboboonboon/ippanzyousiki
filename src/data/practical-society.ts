function make(
  category: "money" | "consumer" | "civic",
  difficulty: Difficulty,
  rows: Entry[],
): Question[] {
  const offset = { easy: 0, normal: 1, hard: 2 }[difficulty];
  return rows.map(
    ([topic, prompt, correct, a, b, c, explanation, key], index) => {
      const answer = (index * 3 + offset) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      const [label, url] = sources[key];
      return {
        id: `v2-${category}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: { label: label + "（2026年9月確認）", url },
      };
    },
  );
}

