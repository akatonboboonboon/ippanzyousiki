function make(theme: "bicycle" | "familiar", rows: Row[]): Question[] {
  const category = theme === "bicycle" ? "public" : "world";
  const topic = theme === "bicycle" ? "自転車の手入れ" : "身近なものの知識";
  const counts: Record<Difficulty, number> = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    ([difficulty, prompt, correct, b, c, d, explanation, ref], index) => {
      const answer = index % 4;
      const choices = [b, c, d];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-living-${theme}-${difficulty}-${String(++counts[difficulty]).padStart(3, "0")}`,
        category,
        topic,
        difficulty,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: ref,
      };
    },
  );
}

