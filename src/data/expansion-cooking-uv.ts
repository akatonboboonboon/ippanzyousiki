function make(
  variant: "cooking" | "uv",
  difficulty: Difficulty,
  rows: Row[],
): Question[] {
  return rows.map(
    ([prompt, correct, a, b, c, explanation, reference], index) => {
      const answer = (index + { easy: 0, normal: 1, hard: 2 }[difficulty]) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-health-everyday-${variant}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category: "health",
        difficulty,
        topic: variant === "cooking" ? "料理の基本" : "紫外線と外出",
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: reference,
      };
    },
  );
}

