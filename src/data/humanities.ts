import type { Question } from "./types";

// Each row stores the correct answer first. The builder rotates choices so the
// answer position does not give away the answer across a question set.
type Row = readonly [
  string,
  string,
  string,
  string,
  string,
  string,
  Question["source"]?,
];

function bank(
  category: Question["category"],
  difficulty: Question["difficulty"],
  rows: readonly Row[],
): Question[] {
  return rows.map(
    ([prompt, correct, wrong1, wrong2, wrong3, explanation, source], index) => {
      const original = [correct, wrong1, wrong2, wrong3];
      const answer = index % 4;
      const choices = Array.from(
        { length: 4 },
        (_, position) => original[(position - answer + 4) % 4],
      ) as Question["choices"];
      return {
        id: `${category}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        prompt,
        choices,
        answer,
        explanation,
        ...(source ? { source } : {}),
      };
    },
  );
}

