// Rows keep the correct choice first for editorial review. A fixed rotation varies
// its displayed position without changing IDs or relying on runtime randomness.
function questions(
  category: Question["category"],
  key: string,
  topic: string,
  rows: Row[],
): Question[] {
  const counters: Record<Difficulty, number> = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    ([difficulty, prompt, candidates, explanation, evidence, image], index) => {
      const answer = index % 4;
      const choices = [
        ...candidates.slice(4 - answer),
        ...candidates.slice(0, 4 - answer),
      ] as Question["choices"];
      return {
        id: `v2-${category}-depth-${key}-${difficulty}-${String(++counters[difficulty]).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices,
        answer,
        explanation,
        source: evidence,
        ...(image ? { image } : {}),
      };
    },
  );
}

