function build(
  category: ActiveCategoryId,
  key: string,
  topic: string,
  rows: Row[],
): Question[] {
  const counts: Record<Difficulty, number> = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    (
      [difficulty, prompt, correct, b, c, d, explanation, source, imageKey],
      index,
    ) => {
      const options = [correct, b, c, d];
      const answer = index % 4;
      const choices = options.map(
        (_, i) => options[(i - answer + 4) % 4],
      ) as Question["choices"];
      const sequence = String(++counts[difficulty]).padStart(3, "0");
      return {
        id: `v2-${category}-depth-${key}-${difficulty}-${sequence}`,
        category,
        difficulty,
        topic,
        prompt,
        choices,
        answer,
        explanation,
        source,
        ...(imageKey ? { image: images[imageKey] } : {}),
      };
    },
  );
}

