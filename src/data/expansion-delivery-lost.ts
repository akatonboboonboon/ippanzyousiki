type Entry = [
  Difficulty,
  string,
  string,
  string,
  string,
  string,
  string,
  keyof typeof sources,
];

function group(
  theme: "lost" | "parcel",
  topic: string,
  rows: Entry[],
): Question[] {
  const counts: Record<Difficulty, number> = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    ([difficulty, prompt, correct, a, b, c, explanation, source]) => {
      const index = ++counts[difficulty];
      const answer =
        (index -
          1 +
          (difficulty === "normal" ? 1 : difficulty === "hard" ? 2 : 0)) %
        4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-public-everyday-${theme}-${difficulty}-${String(index).padStart(3, "0")}`,
        category: "public",
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: sources[source],
      };
    },
  );
}

