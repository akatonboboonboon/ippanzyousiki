type Entry = [
  prompt: string,
  correct: string,
  other1: string,
  other2: string,
  other3: string,
  explanation: string,
  source?: NonNullable<Question["source"]>,
];

function makeQuestions(
  category: "society" | "culture",
  difficulty: Question["difficulty"],
  entries: Entry[],
): Question[] {
  return entries.map(
    ([prompt, correct, other1, other2, other3, explanation, source], index) => {
      const ordered = [correct, other1, other2, other3];
      const answer =
        (index * 3 +
          (difficulty === "normal" ? 1 : difficulty === "hard" ? 2 : 0)) %
        4;
      const choices = [0, 1, 2, 3].map(
        (choice) => ordered[(choice - answer + 4) % 4],
      ) as Question["choices"];
      return {
        id: `${category}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        prompt,
        choices,
        answer,
        explanation,
        ...(source ? { source } : {}),
      };
    },
  );
}

