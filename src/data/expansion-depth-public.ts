type Entry = [
  string,
  string,
  string,
  string,
  string,
  string,
  keyof typeof sources,
  Question["image"]?,
];
function group(
  category: CategoryId,
  key: string,
  topic: string,
  difficulty: Difficulty,
  rows: Entry[],
): Question[] {
  return rows.map(
    ([prompt, correct, a, b, c, explanation, source, image], i) => {
      const answer =
        (i + ({ easy: 1, normal: 2, hard: 3 } as const)[difficulty]) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-depth-${key}-${difficulty}-${String(i + 1).padStart(3, "0")}`,
        category,
        topic,
        difficulty,
        prompt:
          key === "dealsmore"
            ? `${prompt} 金額は税込、記載以外の費用・特典はない。`
            : prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: sources[source],
        ...(image ? { image } : {}),
      };
    },
  );
}
