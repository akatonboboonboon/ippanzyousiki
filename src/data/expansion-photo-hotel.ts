function build(key: "photo" | "hotel", rows: Row[]): Question[] {
  const counts = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    (
      [
        difficulty,
        prompt,
        correct,
        wrong1,
        wrong2,
        wrong3,
        explanation,
        source,
        alt,
      ],
      index,
    ) => {
      const number = ++counts[difficulty];
      const answer = index % 4;
      const choices = [wrong1, wrong2, wrong3];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${key === "photo" ? "digital" : "public"}-familiar-${key}-${difficulty}-${String(number).padStart(3, "0")}`,
        category: key === "photo" ? "digital" : "public",
        difficulty,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source,
        topic: key === "photo" ? "スマホの写真・撮影" : "宿泊の部屋選び",
        ...(alt
          ? {
              image: {
                src: `quiz/familiar-${key}-${String(number).padStart(2, "0")}.svg`,
                alt,
                caption: "撮影画面・客室条件を簡略化した独自の図",
              },
            }
          : {}),
      };
    },
  );
}

