function build(category: Question["category"], entries: Entry[]): Question[] {
  return entries.map(
    (
      [
        difficulty,
        topic,
        prompt,
        correct,
        wrong1,
        wrong2,
        wrong3,
        explanation,
        source,
      ],
      index,
    ) => {
      const answer = (index * 3 + 1) % 4;
      const alternatives = [wrong1, wrong2, wrong3];
      alternatives.splice(answer, 0, correct);
      return {
        id: `v2-${category}-extra-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: alternatives as Question["choices"],
        answer,
        explanation,
        source: sources[source],
      };
    },
  );
}

