// Each authored row puts the answer first; rotate it when constructing the bank.
function group(
  category: "science" | "information" | "life",
  difficulty: Question["difficulty"],
  rows: Row[],
): Question[] {
  const categoryOffset = { science: 0, information: 3, life: 6 }[category];
  const difficultyOffset = { easy: 0, normal: 1, hard: 2 }[difficulty];
  return rows.map(
    ([prompt, correct, wrong1, wrong2, wrong3, explanation, source], index) => {
      const answer = (index + categoryOffset + difficultyOffset) % 4;
      const original = [correct, wrong1, wrong2, wrong3];
      const choices = original.map(
        (_, position) => original[(position - answer + 4) % 4],
      ) as Question["choices"];
      return {
        id: `${category}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        prompt,
        choices,
        answer,
        explanation,
        ...(source ? { source } : {}),
      };
    },
  );
}

