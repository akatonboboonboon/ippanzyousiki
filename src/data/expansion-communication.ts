import type { Difficulty, Question } from "./types";

type Category = "work" | "manners" | "public" | "culture";
type Source = NonNullable<Question["source"]>;
// Each authored row supplies its correct choice first. Rotation avoids answer-position bias.
type Row = [
  Difficulty,
  string,
  string,
  string,
  string,
  string,
  string,
  Source?,
];
const ref = (label: string, url: string): Source => ({ label, url });
const counters: Record<string, number> = {};
let position = 0;
function group(
  category: Category,
  topic: string,
  source: Source,
  rows: Row[],
): Question[] {
  return rows.map(
    ([difficulty, prompt, correct, b, c, d, explanation, rowSource]) => {
      const key = `${category}-${difficulty}`;
      const serial = (counters[key] = (counters[key] ?? 0) + 1);
      const answer = position++ % 4;
      const choices = [b, c, d];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-expanded-${difficulty}-${String(serial).padStart(3, "0")}`,
        category,
        difficulty,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        topic,
        source: rowSource ?? source,
      };
    },
  );
}
