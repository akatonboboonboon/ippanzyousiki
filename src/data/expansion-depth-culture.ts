function group(
  category: Question["category"],
  key: string,
  topic: string,
  entries: Entry[],
): Question[] {
  const counts = { easy: 0, normal: 0, hard: 0 };
  return entries.map(
    ([difficulty, prompt, correctFirst, explanation, source, image], index) => {
      const answer = index % 4;
      const [correct, ...rest] = correctFirst;
      const others: string[] = rest;
      others.splice(answer, 0, correct);
      return {
        id: `v2-${category}-depth-${key}-${difficulty}-${String(++counts[difficulty]).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: others as Question["choices"],
        answer,
        explanation,
        source,
        ...(image ? { image } : {}),
      };
    },
  );
}
