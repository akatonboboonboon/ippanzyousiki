type Entry = [
  string,
  string,
  string,
  string,
  string,
  string,
  keyof typeof sources,
  Question["image"]?,
];

function group(
  key: "bedding" | "appliance",
  difficulty: Difficulty,
  entries: Entry[],
  offset: number,
): Question[] {
  return entries.map(
    ([prompt, correct, a, b, c, explanation, source, image], i) => {
      const answer = (i + offset) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-household-scene-${key}-${difficulty}-${String(i + 1).padStart(3, "0")}`,
        category: "household",
        difficulty,
        topic: key === "bedding" ? "衣類・寝具の形と用途" : "家電の運転機能",
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: sources[source],
        ...(image ? { image } : {}),
      };
    },
  );
}

