function build(
  category: "money" | "digital",
  key: "utilities" | "news",
  topic: string,
  entries: Entry[],
): Question[] {
  const counters: Record<Difficulty, number> = { easy: 0, normal: 0, hard: 0 };
  const offset: Record<Difficulty, number> = { easy: 0, normal: 2, hard: 1 };
  return entries.map(
    ([
      difficulty,
      prompt,
      correct,
      wrong1,
      wrong2,
      wrong3,
      explanation,
      source,
    ]) => {
      const n = ++counters[difficulty];
      const answer =
        (n - 1 + offset[difficulty] + (category === "digital" ? 1 : 0)) % 4;
      const choices = [wrong1, wrong2, wrong3];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-daily-${key}-${difficulty}-${String(n).padStart(3, "0")}`,
        category,
        difficulty,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        topic,
        source: sources[source],
      };
    },
  );
}

