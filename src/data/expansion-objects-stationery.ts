type Entry = [
  string,
  string,
  string,
  string,
  string,
  string,
  keyof typeof sources,
  Question["image"]?,
];
const image = (
  key: string,
  number: number,
  alt: string,
): Question["image"] => ({
  src: `quiz/familiar-${key}-${String(number).padStart(2, "0")}.svg`,
  alt,
  caption: "形や表示を簡略化した模式図",
});
function group(
  key: "smallitems" | "stationery",
  difficulty: Difficulty,
  entries: Entry[],
  offset: number,
): Question[] {
  return entries.map(
    ([prompt, correct, a, b, c, explanation, source, picture], i) => {
      const answer = (i + offset) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      const category = key === "smallitems" ? "household" : "work";
      return {
        id: `v2-${category}-familiar-${key}-${difficulty}-${String(i + 1).padStart(3, "0")}`,
        category,
        difficulty,
        topic: key === "smallitems" ? "日用小物の形と用途" : "文具の選び方",
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: sources[source],
        ...(picture ? { image: picture } : {}),
      };
    },
  );
}

