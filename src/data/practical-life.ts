type Row = [
  topic: string,
  prompt: string,
  correct: string,
  wrong1: string,
  wrong2: string,
  wrong3: string,
  explanation: string,
  source: keyof typeof sources,
];
function batch(
  category: "household" | "health" | "safety",
  difficulty: Difficulty,
  rows: Row[],
): Question[] {
  return rows.map(
    ([topic, prompt, correct, a, b, c, explanation, source], i) => {
      const answer =
        (i + (difficulty === "normal" ? 1 : difficulty === "hard" ? 2 : 0)) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-${difficulty}-${String(i + 1).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: sources[source],
      };
    },
  );
}

