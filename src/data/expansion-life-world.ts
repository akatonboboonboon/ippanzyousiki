import type { ActiveCategoryId, Difficulty, Question } from "./types";

type Source = NonNullable<Question["source"]>;
type Row = [string, string, string, string, string, string, Source?];
const source = (label: string, url: string): Source => ({ label, url });
const counters: Record<string, number> = {};
// Each group has two easy, two normal and one hard question. Keep published rows in order.
function group(
  category: ActiveCategoryId,
  topic: string,
  reference: Source,
  rows: [Row, Row, Row, Row, Row],
): Question[] {
  return rows.map(
    ([prompt, correct, a, b, c, explanation, ownSource], index) => {
      const difficulty: Difficulty =
        index < 2 ? "easy" : index < 4 ? "normal" : "hard";
      const key = `${category}-${difficulty}`;
      const serial = (counters[key] ?? 0) + 1;
      counters[key] = serial;
      const answer = (serial + index) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-expanded-${difficulty}-${String(serial).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: ownSource ?? reference,
      };
    },
  );
}

