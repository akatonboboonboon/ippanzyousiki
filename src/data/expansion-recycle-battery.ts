function make(
  key: "recycle" | "battery",
  difficulty: Difficulty,
  rows: Row[],
): Question[] {
  return rows.map(
    ([prompt, correct, a, b, c, explanation, reference], index) => {
      const answer = (index + { easy: 0, normal: 2, hard: 0 }[difficulty]) % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-household-living-${key}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category: "household",
        difficulty,
        topic: key === "recycle" ? "家電の処分" : "乾電池の使い方",
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: reference,
      };
    },
  );
}

