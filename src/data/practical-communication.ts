type Ref = keyof typeof refs;
type Row = [
  topic: string,
  prompt: string,
  correct: string,
  wrong1: string,
  wrong2: string,
  wrong3: string,
  explanation: string,
  ref?: Ref,
];
function bank(
  category: Question["category"],
  difficulty: Question["difficulty"],
  rows: Row[],
  fallback: Ref,
): Question[] {
  return rows.map(
    ([topic, prompt, correct, a, b, c, explanation, ref], index) => {
      const answer = index % 4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: refs[ref ?? fallback],
      };
    },
  );
}

