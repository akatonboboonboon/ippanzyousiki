type Entry = [
  Difficulty,
  string,
  string,
  string,
  string,
  string,
  string,
  keyof typeof sources,
];
function build(
  category: "consumer" | "health",
  key: "rent" | "label",
  topic: string,
  rows: Entry[],
): Question[] {
  const counts = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    ([difficulty, prompt, correct, a, b, c, explanation, source]) => {
      const number = ++counts[difficulty];
      const answer =
        (number -
          1 +
          (difficulty === "normal" ? 1 : difficulty === "hard" ? 2 : 0)) %
        4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-living-${key}-${difficulty}-${String(number).padStart(3, "0")}`,
        category,
        topic,
        difficulty,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: sources[source],
      };
    },
  );
}

