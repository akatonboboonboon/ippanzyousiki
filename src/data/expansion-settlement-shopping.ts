function makeQuestions(
  rows: Row[],
  category: "money" | "consumer",
  key: string,
  topic: string,
): Question[] {
  const counts: Record<Difficulty, number> = { easy: 0, normal: 0, hard: 0 };
  return rows.map(
    ([difficulty, prompt, correct, b, c, d, explanation, source], index) => {
      const answer = index % 4;
      const choices = [b, c, d];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-scene-${key}-${difficulty}-${String(++counts[difficulty]).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source,
      };
    },
  );
}
