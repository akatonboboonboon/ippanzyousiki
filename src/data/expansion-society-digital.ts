function build(
  category: Question["category"],
  difficulty: Difficulty,
  rows: Entry[],
): Question[] {
  return rows.map(
    ([topic, prompt, correct, a, b, c, explanation, source], index) => {
      const answer =
        (index +
          (difficulty === "easy" ? 0 : difficulty === "normal" ? 1 : 2)) %
        4;
      const choices = [a, b, c];
      choices.splice(answer, 0, correct);
      return {
        id: `v2-${category}-expanded-${difficulty}-${String(index + 1).padStart(3, "0")}`,
        category,
        difficulty,
        topic,
        prompt,
        choices: choices as Question["choices"],
        answer,
        explanation,
        source: { label: sources[source][0], url: sources[source][1] },
      };
    },
  );
}
